# 事实性数字的识别口径：带金额/比例/算力单位的数字，以及四位数以上的量级
# （队伍数、star 数、参数量）。年份（19xx/20xx）不算，日期里的月日也不算。
_INDUSTRY_UNIT_RE = re.compile(
    r"(\d[\d,]*(?:\.\d+)?)\s*(?:万亿|亿|万|千|百|美元|美金|元|港元|人民币|"
    r"%|％|倍|个百分点|TOPS|PFLOPS|EFLOPS|GB|TB)")
_YEAR_TOKEN_RE = re.compile(r"^(?:19|20)\d{2}$")


def _industry_texts(spec: dict) -> list[str]:
    texts = [str(spec.get("title") or ""), str(spec.get("digest") or ""),
             str(spec.get("subtitle") or ""), str(spec.get("takeaway") or "")]
    texts.extend(str(p) for p in (spec.get("lead") or []) if isinstance(p, str))
    for block in spec.get("sections") or []:
        if not isinstance(block, dict):
            continue
        kind = block.get("type")
        if kind == "code":
            continue
        if kind == "meta_card":
            for row in block.get("rows") or []:
                texts.extend(str(c) for c in (row or []))
            continue
        if kind == "table":
            texts.extend(str(c) for c in block.get("header") or [])
            for row in block.get("rows") or []:
                texts.extend(str(c) for c in (row or []))
            continue
        for key in ("text", "caption", "title"):
            if block.get(key):
                texts.append(str(block[key]))
        texts.extend(str(i) for i in block.get("items") or [])
    return texts


def _material_sentence_lines(items: list) -> list[list[float]]:
    """素材里「同一句话内的数字」：金额差值（300 亿 - 200 亿 = 100 亿）在这里成立。"""
    lines: list[list[float]] = []
    for item in items:
        extra = getattr(item, "extra", {}) or {}
        texts = [getattr(item, "title", "") or "", getattr(item, "summary", "") or "",
                 str(extra.get("full_text") or "")]
        for text in texts:
            for sentence in re.split(r"(?<=[。！？!?；;])|\n", str(text)):
                nums = []
                for tok in _NUM_TOKEN_RE.findall(sentence):
                    try:
                        nums.append(float(tok.replace(",", "")))
                    except ValueError:
                        continue
                if len(nums) >= 2:
                    lines.append(nums)
    return lines


def _amount_explained(tok: str, pool: set[str], lines: list[list[float]]) -> bool:
    if tok in pool:
        return True
    try:
        target = float(tok)
    except ValueError:
        return False
    decimals = len(tok.split(".")[1]) if "." in tok else 0
    for raw in pool:
        try:
            if round(float(raw), decimals) == target:
                return True
        except ValueError:
            continue
    # 同一句素材里两个数相减/相加能得到它：这是合法的换算，不算编造
    for line in lines:
        for i, a in enumerate(line):
            for b in line[i + 1:]:
                if round(abs(a - b), decimals) == target or round(a + b, decimals) == target:
                    return True
    return False


def unsupported_industry_numbers(spec: dict, items: list) -> list[str]:
    """业界稿里「素材原文找不到」的事实性数字（金额 / 比例 / 算力 / 千级量级）。

    只查事实性数字，不查「三条路线」这类序数词和「6–18 个月」这类区间估计——
    范围放太宽会把正常行文也标红，重写一次反而更差。
    """
    pool = material_number_pool(items)
    lines = _material_sentence_lines(items)
    bad: list[str] = []
    for text in _industry_texts(spec):
        for m in _INDUSTRY_UNIT_RE.finditer(text):
            tok = m.group(1).replace(",", "")
            if _YEAR_TOKEN_RE.match(tok) or tok in bad:
                continue
            if not _amount_explained(tok, pool, lines):
                bad.append(tok)
        for m in _NUM_TOKEN_RE.finditer(text):
            tok = m.group(0).replace(",", "")
            if tok in bad or _YEAR_TOKEN_RE.match(tok):
                continue
            try:
                value = float(tok)
            except ValueError:
                continue
            if value < 1000:      # 千级以下只查带单位的（上面已覆盖）
                continue
            if not _amount_explained(tok, pool, lines):
                bad.append(tok)
    return bad


def _featured_item(spec_title: str, items: list):
    """按标题相似度找出成稿头条对应的素材条目（模型会自选头条，未必是 selected[0]）。"""
    from difflib import SequenceMatcher

    clean = re.sub(
        r"^\s*(?:【[^】]{0,24}】|[A-Za-z][A-Za-z/ &]{0,20}\s*20\d{2}\s*[|｜：:]?\s*)",
        "", spec_title).lower()[:80]
    best, best_r = None, -1.0
    for it in items:
        ratio = SequenceMatcher(None, clean, (it.title or "").lower()[:80]).ratio()
        if ratio > best_r:
            best, best_r = it, ratio
    return best


