def _cell_numbers(cell: str) -> list[float]:
    nums: list[float] = []
    for tok in _NUM_TOKEN_RE.findall(str(cell)):
        try:
            nums.append(float(tok.replace(",", "")))
        except ValueError:
            continue
    return nums


def _material_number_groups(items: list) -> list[tuple[set[float], list[list[float]]]]:
    """每张素材表/每条数值结论句：数值集合 + 同行同列（同句内）的数值分组。

    差值只允许在同一行、同一列或同一句里成立。一张 9 列表里任意两数相减，
    两位小数几乎总能凑出目标值（实测 2.81 被 22.87-25.68 蒙中），那样闸门等于没有。
    """
    groups: list[tuple[set[float], list[list[float]]]] = []
    for item in items:
        extra = getattr(item, "extra", {}) or {}
        for table in extra.get("tables") or []:
            header = [str(c) for c in (table.get("header") or [])]
            rows = [[str(c) for c in (row or [])] for row in (table.get("rows") or [])]
            values: set[float] = set()
            lines: list[list[float]] = []
            columns: dict[int, list[float]] = {}
            for ci, cell in enumerate(header):
                nums = _cell_numbers(cell)
                values.update(nums)
                columns.setdefault(ci, []).extend(nums)
            for row in rows:
                line: list[float] = []
                for ci, cell in enumerate(row):
                    nums = _cell_numbers(cell)
                    values.update(nums)
                    line.extend(nums)
                    columns.setdefault(ci, []).extend(nums)
                lines.append(line)
            lines.extend(columns.values())
            groups.append((values, lines))
        for snippet in extra.get("result_snippets") or []:
            nums = _cell_numbers(snippet)
            if len(nums) >= 2:
                groups.append((set(nums), [nums]))
    return groups


def _metric_name(text: str) -> str:
    """表头/正文的指标名归一：中文（精确率）、缩写（Precision）、
    两行表头合并后的紧凑名（P@0.5）都归到同一个键。"""
    text = str(text)
    compact = re.match(r"^\s*([RP])@(\d+(?:\.\d+)?)", text, re.I)
    if compact:
        return "RECALL" if compact.group(1).upper() == "R" else "PRECISION"
    m = _METRIC_RE.search(text)
    if not m:
        return ""
    return _METRIC_ALIASES.get(m.group(0).upper().strip(), m.group(0).upper())


def _metric_lines(items: list) -> dict[str, list[list[float]]]:
    """按指标名归拢素材表里的数值行与数值列，供「差值必须落在同名指标内」核对。

    只看「同一行/同一列」仍然太宽：实测 2.82 被一张无关表里 39.35-36.53 蒙中，
    而正文那句话讲的是 MUSIQ。行标签/表头带指标名时，差值只在该指标的数值里找。
    """
    out: dict[str, list[list[float]]] = {}

    def add(name: str, nums: list[float]) -> None:
        if len(nums) >= 2:
            out.setdefault(name, []).append(nums)

    for item in items:
        extra = getattr(item, "extra", {}) or {}
        for table in extra.get("tables") or []:
            header = [str(c) for c in (table.get("header") or [])]
            rows = [[str(c) for c in (row or [])] for row in (table.get("rows") or [])]
            for row in rows:
                name = _metric_name(" ".join(row[:2]))
                if name:
                    add(name, [n for cell in row[1:] for n in _cell_numbers(cell)])
            for ci, cell in enumerate(header):
                name = _metric_name(cell)
                if not name:
                    continue
                add(name, [n for row in rows if ci < len(row)
                           for n in _cell_numbers(row[ci])])
    return out


def _explained_by_material(tok: str, pool: set[str],
                           groups: list[tuple[set[float], list[list[float]]]],
                           scoped: list[list[float]] | None = None) -> bool:
    """素材原值、原值的舍入、同一张表同行同列（或同一句）两数之差，都算可核对。"""
    if tok in pool:
        return True
    try:
        target = float(tok)
    except ValueError:
        return False
    decimals = len(tok.split(".")[1])
    for values, lines in groups:
        if any(round(n, decimals) == target for n in values):
            return True
    def _diff_in(lines: list[list[float]]) -> bool:
        return any(round(abs(a - b), decimals) == target
                   for line in lines for i, a in enumerate(line) for b in line[i + 1:])

    if scoped:
        # 同名指标（含跨表）：正文写「精确率由 80.22% 升至 84.00%，提高 3.78」时，
        # 两个原值常分属基线表与本文表——按「同名指标」归拢后允许并集内两数相减。
        # 这仍然安全：2.82 那类事故是拿无关表的 PSNR 差蒙 MUSIQ 的差值，
        # 指标名不同就进不了同一个并集。
        flat: list[float] = []
        for line in scoped:
            flat.extend(line)
        if _diff_in([flat]):
            return True
        # scoped 没对上时仍要回同表同行/同列闸门再核一遍：
        # 紧凑表头（P@0.5）之外的列不在指标并集里，但同一列内的两数之差依然合法
        # （IoU 表「精确率 86.33→92.77，提升 6.44」正是同一列跨行差）。
    for _values, lines in groups:
        if _diff_in(lines):
            return True
    return False


def unsupported_prose_numbers(spec: dict, items: list) -> list[str]:
    """03/04 节正文里对不上素材的小数（实测多为模型算错的差值，如 2.78 写成 2.81）。"""
    pool = material_number_pool(items)
    groups = _material_number_groups(items)
    metric_lines = _metric_lines(items)
    bad: list[str] = []
    in_evidence = False
    for block in spec.get("sections") or []:
        if not isinstance(block, dict):
            continue
        kind = block.get("type")
        text = str(block.get("text") or "")
        if kind in ("h2", "h3"):
            in_evidence = bool(_EVIDENCE_HEAD_RE.match(text.strip()))
            continue
        if not in_evidence or kind == "table":
            continue
        blob = text + " " + " ".join(str(x) for x in (block.get("items") or []))
        # 按句核对 + 指标就近归属。实测三种语序都要认：
        # 「精确率由 80.22% 升至 84.00%，提高 3.78」（句内指标在前）；
        # 「以极小的改动换取 0.0146 的 F1 提升」（指标在后）；
        # 「前视图 F1 为 0.8376…；俯视图上由 0.9691 升至 0.9817，提升 0.0126」
        # （本句没有指标名，承前句的 F1）。句内没有指标时继承上一句的归属，
        # 但不许跳段——「一段里连写三组对比」靠句界隔开，不会张冠李戴。
        last_name = ""
        for sent in re.split(r"(?<=[。；！？!?])", blob):
            metrics = [(m.start(), m.group(0).upper()) for m in _METRIC_RE.finditer(sent)]
            sentence_name = ""
            for m in _PROSE_NUM_RE.finditer(sent):
                tok = m.group(0)
                if tok in bad:
                    continue
                name = ""
                before = [it for it in metrics if it[0] < m.start()]
                if before:
                    name = before[-1][1]
                else:
                    after = [it for it in metrics if it[0] > m.start()]
                    if after:
                        name = after[0][1]
                if not name:
                    name = last_name
                if name:
                    sentence_name = name
                # 正文可能写中文（「精确率」）、表头写英文（"Precision (%)"）：
                # 统一经别名表归一到同一指标键，跨表差值才能对上
                scoped = metric_lines.get(_metric_name(name) or name)
                if not _explained_by_material(tok, pool, groups, scoped):
                    bad.append(tok)
            last_name = sentence_name or last_name
    return bad


def quant_retry_instruction(bad_numbers: list[str], has_material: bool = True) -> str:
    """二次重写的附加指令：缺数值证据 / 表格里编了数字 / 素材本就没有数字。"""
    if not has_material:
        return NO_NUMERIC_RETRY
    if not bad_numbers:
        return QUANT_RETRY
    return QUANT_RETRY + (
        "\n5) 上一稿的实验解读里出现了素材中不存在的数字（"
        + "、".join(bad_numbers[:8])
        + "），这些是编造的。表格只能照抄素材 tables 里的单元格；正文只能用素材原值，"
        "差值要拿素材同一张表里的两个数逐位相减并核对，凑不出就并列两个原始数字、不要硬写差值。"
    )



def _item_payload(index: int, item, figure_ids: list[str]) -> dict:
    payload = {
        "id": f"P{index}",
        "title": item.title,
        "url": item.url,
        "source": item.source,
        "venue": item.venue,
        "year": item.year,
        "authors": item.authors[:8],
        "category": item.category,
        "abstract": (item.summary or "")[:1600],
        "code_url": item.code_url,
        "score": item.score,
        "keywords": item.keywords[:8],
        "figures": figure_ids,
    }
    if item.published_at:
        payload["published"] = item.published_at.strftime("%Y-%m-%d")
    # 业界稿的正文（选中后回抓）：量子位首页只有一句摘要，没有这段写不出事实密度
    if item.extra.get("full_text"):
        # 指定论文给全文 6000 字：单篇精读全靠它，3000 字撑不起「问题—方法—证据」
        limit = 6000 if item.module == "paper" else 3000
        payload["full_text"] = str(item.extra["full_text"])[:limit]
    if item.module == "paper" and item.extra.get("targeted"):
        payload["targeted"] = True
        if item.extra.get("doi"):
            payload["doi"] = item.extra["doi"]
        if item.extra.get("citations"):
            payload["citations"] = item.extra["citations"]
        if item.extra.get("publication"):
            payload["publication"] = item.extra["publication"]
    if item.extra.get("deadline"):
        payload["deadline"] = item.extra["deadline"]
    if item.extra.get("prize"):
        payload["prize"] = item.extra["prize"]
    if item.extra.get("platform"):
        payload["platform"] = item.extra["platform"]
    if item.extra.get("figure_caption"):
        payload["figure_caption"] = item.extra["figure_caption"]
    if item.extra.get("figure_caption_2"):
        payload["figure_caption_2"] = item.extra["figure_caption_2"]
    tables = item.extra.get("tables") or []
    if tables:
        # 素材表先压到移动端口径（表头 + 4 个核心指标列）再给模型：
        # 模型会照抄输入表的形态，喂 9 列它就吐 9 列。数字校验仍用未裁剪的原始表，
        # 所以正文引用被裁掉的指标数值也能核对通过。
        payload["tables"] = compact_tables(tables[:3])
    snippets = item.extra.get("result_snippets") or []
    if snippets:
        payload["result_snippets"] = snippets
    # days_left 是按 extra.deadline 算的，未必等于「报名截止」；报名已关时不下发，
    # 否则模型会写出「3 天报名倒计时」这种与正文自相矛盾的标题。
    closed = bool((item.extra.get("contest_detail") or {}).get("registration_closed"))
    if item.extra.get("days_left") is not None and not closed:
        payload["days_left"] = item.extra["days_left"]
    if item.extra.get("organizer"):
        payload["organizer"] = str(item.extra["organizer"])[:60]
    if item.extra.get("entry_url"):
        payload["entry_url"] = str(item.extra["entry_url"])
    if item.extra.get("tags"):
        payload["tags"] = [str(t)[:24] for t in (item.extra["tags"] or [])][:8]
    # 赛题精读的素材底座：官方赛题正文 + 页面摘录 + 时间线 + 评测/奖金原句。
    # 没有这一层，「数据说明 / 评估指标 / 赛事周期 / 奖项」四节只能靠模型编。
    detail = item.extra.get("contest_detail") or {}
    if detail:
        payload["contest_detail"] = {
            "source": str(detail.get("source") or ""),
            "official_brief": str(detail.get("official_brief") or "")[:3500],
            "page_excerpt": str(detail.get("page_excerpt") or "")[:2000],
            "timeline": [str(t) for t in (detail.get("timeline") or [])][:8],
            "prize_hint": [str(t)[:180] for t in (detail.get("prize_hint") or [])][:3],
            "metrics_hint": [str(t)[:180] for t in (detail.get("metrics_hint") or [])][:6],
            "registration_closed": bool(detail.get("registration_closed")),
            "registration_hint": str(detail.get("registration_hint") or ""),
        }
    if item.extra.get("is_learning_resource"):
        payload["is_learning_resource"] = True
        detail = item.extra.get("baseline_detail") or {}
        payload["baseline_detail"] = {
            "files": [f for f in (detail.get("files") or []) if f][:15],
            "readme_excerpt": (detail.get("readme_excerpt") or "")[:3000],
        }
        # README 过短时自动生成的范式推演提示，供成稿做专业推断兜底
        if detail.get("paradigm_hint"):
            payload["baseline_detail"]["paradigm_hint"] = str(detail["paradigm_hint"])[:1200]
        # 联网检索到的赛事官方背景：赛题信息查证后确定性撰写的事实依据
        ctx = detail.get("search_context") or []
        if ctx:
            payload["baseline_detail"]["search_context"] = [
                {"title": str(c.get("title") or "")[:120],
                 "snippet": str(c.get("snippet") or "")[:400],
                 "url": str(c.get("url") or "")}
                for c in ctx[:4]
            ]
        # 关键代码片段是 baseline 精读的核心素材，必须原样传给模型
        samples = detail.get("code_samples") or []
        if samples:
            payload["baseline_detail"]["code_samples"] = [
                {"name": str(s.get("name") or ""), "code": str(s.get("code") or "")[:2200]}
                for s in samples[:3] if s.get("code")
            ]
    # NTIRE 官方报告：赛道定义 + 榜单 + 冠军方案 + 社区复盘，四块拼成完整素材底座
    report = item.extra.get("ntire_report")
    if report:
        champ = report.get("champion") or {}
        stats = report.get("stats") or {}
        payload["ntire_report"] = {
            "conference": str(item.extra.get("conference") or ""),
            "report_title": str(item.extra.get("report_title") or item.title)[:200],
            "track": str(item.extra.get("track") or ""),
            "year": str(item.extra.get("year") or ""),
            "abstract": str(report.get("abstract") or "")[:2400],
            "report_excerpt": str(report.get("report_excerpt") or "")[:6000],
            "sections": [
                {"num": str(s.get("num") or ""), "method": str(s.get("method") or "")[:180],
                 "team": str(s.get("team") or "")[:90]}
                for s in (report.get("sections") or [])[:6]
            ],
            "leaderboard": [
                {"rank": r.get("rank"), "team": str(r.get("team") or "")[:60],
                 "score": str(r.get("score") or "")}
                for r in (report.get("leaderboard") or [])[:5]
            ],
            "champion": {"rank": champ.get("rank"), "team": str(champ.get("team") or "")[:80],
                         "method": str(champ.get("method") or "")[:180],
                         "score": str(champ.get("score") or "")},
            "stats": {k: stats[k] for k in ("participants", "participants_hint", "submissions",
                                            "tracks", "metrics") if stats.get(k)},
            "benchmark": [str(b)[:400] for b in (report.get("benchmark") or [])[:3]],
            "results_table": str(report.get("results_table") or "")[:1600],
            "community": [
                {"title": str(c.get("title") or "")[:140],
                 "snippet": str(c.get("snippet") or "")[:360],
                 "url": str(c.get("url") or ""),
                 "source": str(c.get("source") or ""),
                 "same_track": bool(c.get("same_track", True))}
                for c in (report.get("community") or [])[:5]
            ],
            "report_url": str(report.get("pdf_url") or "")[:300],
        }
    # 论文发表状态（检索查证结论）：标题与信息卡的 venue 以此为准
    pub = item.extra.get("publication")
    if pub:
        payload["publication"] = pub
    return payload


def build_user_prompt(module: str, items: list, figures: dict[str, dict], date_str: str,
                      variant: str | None = None) -> str:
    """把素材整理成模型友好的 JSON，附带图片编号表。variant 用于模块内成稿变体。"""
    import json

    material = []
    for idx, item in enumerate(items, 1):
        ids = [fid for fid, meta in figures.items() if meta.get("item_id") == f"{item.module}:{item.fingerprint}"]
        material.append(_item_payload(idx, item, ids))

    figure_table = [
        {"ref": fid, "caption": meta.get("caption", "")[:200], "from": meta.get("title", "")[:80]}
        for fid, meta in figures.items()
    ]

    payload = {
        "date": date_str,
        "module": module,
        "variant": variant or "default",
        "brand": {"name": BRAND_NAME, "slogan": SLOGAN},
        "materials": material,
        "figures": figure_table,
    }
    prompt_key = f"{module}_{variant}" if (module == "contest" and variant == "baseline") else module
    # baseline 精读有两种素材：Datawhale 的复现仓库 → 讲代码起点；
    # NTIRE 官方报告 → 讲赛道定义与冠军方案。两者结构完全不同，不能共用一套 Prompt。
    if prompt_key == "contest_baseline" and any(
            (m.get("ntire_report") or {}) for m in material if isinstance(m, dict)):
        prompt_key = "contest_ntire"
    prompt_text = PROMPTS[prompt_key]
    # 指定论文名称检索成稿：追加「只写这一篇」铁律（规范全部继承，不另立门户）
    if prompt_key == "paper" and any(
            m.get("targeted") for m in material if isinstance(m, dict)):
        prompt_text += TARGETED_PAPER_RULES
    return (
        prompt_text
        + "\n\n【本期素材】\n"
        + json.dumps(payload, ensure_ascii=False, indent=2)
        + "\n\n请严格按上述 JSON 规格输出，只输出 JSON。"
    )
