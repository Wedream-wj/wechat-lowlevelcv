# 最长词长度：标题级文本不需要更长的原子，超过 6 字的多半是短语而非词
_MAX_LEN = min(6, max(len(w) for w in _WORDS))


def segment_cjk(run: str) -> list[str]:
    """把一段连续中文切成词原子：最长匹配（正向），未登录字退回单字。

    例：segment_cjk("用梯度引导补齐红外超分") →
        ["用", "梯度", "引导", "补齐", "红外", "超分"]
    """
    out: list[str] = []
    i, n = 0, len(run)
    while i < n:
        step = min(_MAX_LEN, n - i)
        while step > 0 and run[i:i + step] not in _WORDS:
            step -= 1
        if step == 0:
            step = 1                      # 未登录字：单字原子，允许在此断行
        out.append(run[i:i + step])
        i += step
    return out


def is_word(atom: str) -> bool:
    """该原子是否是词表里的词（测试与调试用）。"""
    return atom in _WORDS
